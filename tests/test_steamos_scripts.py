"""Exercise database lifecycle and launcher boundaries without installing software."""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest


PROJECT = Path(__file__).resolve().parents[1]
FAKE_TOOL = r'''
import json
import os
from pathlib import Path
import sys

name = Path(sys.argv[0]).name
args = sys.argv[1:]
state = Path(os.environ['CSH_TEST_STATE'])
with (state / 'calls.jsonl').open('a') as output:
    output.write(json.dumps({'name': name, 'args': args,
        'pg_hostaddr': os.environ.get('PGHOSTADDR'),
        'pg_host': os.environ.get('PGHOST'),
        'path': os.environ.get('PATH')}) + '\n')
if name == 'uname':
    print(os.environ.get('CSH_TEST_OS', 'Linux') if args == ['-s'] else 'x86_64')
elif name == 'initdb':
    destination = Path(args[args.index('-D') + 1])
    (destination / 'PG_VERSION').write_text('17\n')
    (destination / 'postgresql.conf').write_text('# generated by initdb\n')
    if os.environ.get('CSH_TEST_INIT_FAIL'):
        sys.exit(1)
elif name == 'pg_ctl':
    running = state / 'running'
    if 'status' in args:
        sys.exit(0 if running.exists() else 3)
    elif 'start' in args:
        if os.environ.get('CSH_TEST_START_FAIL'):
            sys.exit(1)
        running.touch()
    elif 'stop' in args:
        running.unlink()
elif name == 'psql':
    database = state / 'database'
    sql = args[args.index('-c') + 1]
    if sql.startswith('SELECT'):
        if database.exists():
            print('1')
    elif sql == 'CREATE DATABASE csdm':
        database.touch()
'''


@unittest.skipUnless(shutil.which('bash') and hasattr(os, 'geteuid'), 'Requires a POSIX shell')
class SteamOSScriptsTests(unittest.TestCase):
    def setUp(self):
        if os.geteuid() == 0:
            self.skipTest('Scripts intentionally refuse root; run these tests as an ordinary user')
        self.temp = tempfile.TemporaryDirectory(prefix='cs highlights ')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.project = self.root / 'project with spaces'
        shutil.copytree(PROJECT / 'scripts', self.project / 'scripts')
        self.install = self.root / 'installation with spaces'
        self.runtime = self.install / 'runtime'
        self.bin = self.runtime / 'bin'
        self.bin.mkdir(parents=True)
        (self.runtime / '.csh-ready').touch()
        (self.bin / 'python').symlink_to(sys.executable)
        self.state = self.root / 'state'
        self.state.mkdir()
        for name in ('uname', 'flock', 'initdb', 'pg_ctl', 'psql'):
            self.write_tool(self.bin / name)
        self.env = {**os.environ, 'CSH_STEAMOS_HOME': str(self.install),
                    'CSH_TEST_STATE': str(self.state), 'PATH': f'{self.bin}:{os.environ["PATH"]}'}
        self.env.pop('CSH_CONFIG', None)
        self.env.pop('BASH_ENV', None)

    def write_tool(self, path, content=FAKE_TOOL):
        path.write_text(f'#!{sys.executable}\n{content}')
        path.chmod(0o755)

    def call(self, script, *args, **overrides):
        return subprocess.run(['bash', str(self.project / 'scripts' / script), *args],
                              cwd=self.root, env={**self.env, **overrides},
                              capture_output=True, text=True, timeout=10)

    def db(self, action, **overrides):
        return self.call('steamos-postgres.sh', action, **overrides)

    def assert_success(self, result):
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def calls(self, name):
        path = self.state / 'calls.jsonl'
        if not path.exists():
            return []
        return [call for line in path.read_text().splitlines()
                if (call := json.loads(line))['name'] == name]

    def test_appimage_cli_with_release_permissions_can_run_after_install(self):
        # Official v3.20.1 AppImage (SHA-256 95608b6c...65c5115): csdm is
        # a regular shell script with mode 0644; AppRun and Electron are 0755.
        extracted = self.root / 'squashfs-root'
        extracted.mkdir()
        cli = extracted / 'csdm'
        cli.write_text('#!/bin/sh\nELECTRON_RUN_AS_NODE=1 "$(dirname "$0")/cs-demo-manager" '
                       '"$(dirname "$0")/resources/app.asar/cli.js" "$@"\n')
        cli.chmod(0o644)
        self.write_tool(extracted / 'cs-demo-manager')
        self.write_tool(extracted / 'AppRun')
        (extracted / 'resources').mkdir()
        (extracted / 'resources/app.asar').touch()
        common = self.project / 'scripts/steamos-common.sh'
        installed = self.install / 'csdm-3.20.1'
        result = subprocess.run(['bash', '-euc',
                                 'source "$1"; csh_prepare_csdm "$2"; '
                                 'mv -- "$2" "$3"; csh_prepare_csdm "$3"; "$3/csdm" help',
                                 'test', str(common), str(extracted), str(installed)],
                                env=self.env, capture_output=True, text=True, timeout=10)
        self.assert_success(result)
        self.assertEqual(self.calls('cs-demo-manager')[-1]['args'],
                         [str(installed / 'resources/app.asar/cli.js'), 'help'])
        self.assertEqual((installed / 'csdm').stat().st_mode & 0o777, 0o744)

    def test_incomplete_appimage_reports_the_missing_file(self):
        extracted = self.root / 'squashfs-root'
        extracted.mkdir()
        for name in ('csdm', 'AppRun', 'cs-demo-manager'):
            self.write_tool(extracted / name)
        result = subprocess.run(['bash', '-euc', 'source "$1"; csh_prepare_csdm "$2"',
                                 'test', str(self.project / 'scripts/steamos-common.sh'), str(extracted)],
                                env=self.env, capture_output=True, text=True, timeout=10)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(str(extracted / 'resources/app.asar'), result.stderr)

    def test_help_and_wrong_platform_do_not_install_anything(self):
        self.assert_success(self.call('install-steamos.sh', '--help'))
        self.assert_success(self.call('steamos.sh', '--help'))
        result = self.call('install-steamos.sh', CSH_TEST_OS='Darwin')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Linux x86_64', result.stderr)
        self.assertFalse((self.install / 'micromamba').exists())
        self.assertFalse((self.install / 'postgres').exists())

    def test_init_is_private_and_repeatable_without_resetting_data(self):
        self.assert_success(self.db('init'))
        password = self.install / 'postgres-password'
        original = password.read_bytes()
        self.assertEqual(password.stat().st_mode & 0o777, 0o600)
        self.assertGreaterEqual(len(original.strip()), 32)
        data = self.install / 'postgres' / 'keep-me'
        data.write_text('existing matches')
        self.assert_success(self.db('init'))
        self.assertEqual(password.read_bytes(), original)
        self.assertEqual(data.read_text(), 'existing matches')
        self.assertEqual(len(self.calls('initdb')), 1)
        self.assertIn('--auth-host=scram-sha-256', self.calls('initdb')[0]['args'])
        self.assertIn('--auth-local=scram-sha-256', self.calls('initdb')[0]['args'])
        config = (self.install / 'postgres/postgresql.conf').read_text()
        self.assertIn("listen_addresses = '127.0.0.1'", config)
        self.assertIn("unix_socket_directories = ''", config)
        self.assertIn('port = 55432', config)
        self.assertFalse((self.state / 'running').exists())

    def test_failed_init_can_be_retried_and_preserves_password(self):
        self.assertNotEqual(self.db('init', CSH_TEST_INIT_FAIL='1').returncode, 0)
        password = (self.install / 'postgres-password').read_bytes()
        self.assertFalse((self.install / 'postgres').exists())
        self.assertEqual(list(self.install.glob('.postgres-init.*')), [])
        self.assert_success(self.db('init'))
        self.assertEqual((self.install / 'postgres-password').read_bytes(), password)

    def test_start_stop_are_repeatable_and_pg_environment_is_isolated(self):
        self.assert_success(self.db('init'))
        for _ in range(2):
            self.assert_success(self.db('start', PGHOSTADDR='203.0.113.1', PGSERVICE='unrelated'))
        self.assertEqual(sum('start' in call['args'] for call in self.calls('pg_ctl')), 1)
        self.assertEqual(sum('CREATE DATABASE csdm' in call['args'] for call in self.calls('psql')), 1)
        for call in self.calls('psql'):
            self.assertIsNone(call['pg_hostaddr'])
            self.assertEqual(call['pg_host'], '127.0.0.1')
        self.assert_success(self.db('stop'))
        self.assert_success(self.db('stop'))
        self.assertTrue((self.state / 'database').exists())
        self.assertEqual(sum('stop' in call['args'] for call in self.calls('pg_ctl')), 1)

    def test_start_failure_does_not_connect_to_another_database(self):
        self.assert_success(self.db('init'))
        result = self.db('start', CSH_TEST_START_FAIL='1')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('postgres.log', result.stderr)
        self.assertEqual(self.calls('psql'), [])

    def test_refuses_partial_cluster_and_incompatible_version(self):
        cluster = self.install / 'postgres'
        cluster.mkdir()
        (cluster / 'important').write_text('keep')
        result = self.db('init')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('no se sobrescribe', result.stderr)
        (cluster / 'PG_VERSION').write_text('16\n')
        result = self.db('init')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('PostgreSQL 17', result.stderr)
        self.assertEqual(self.calls('initdb'), [])
        self.assertEqual((cluster / 'important').read_text(), 'keep')

    def test_existing_cluster_never_gets_a_replacement_password(self):
        self.assert_success(self.db('init'))
        (self.install / 'postgres-password').unlink()
        result = self.db('init')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('no se genera otra', result.stderr)
        self.assertFalse((self.install / 'postgres-password').exists())

    def test_credentials_is_explicit_and_does_not_start_server(self):
        self.assert_success(self.db('init'))
        password = (self.install / 'postgres-password').read_text().strip()
        result = self.call('steamos.sh', 'db', 'credentials')
        self.assert_success(result)
        self.assertIn(password, result.stdout)
        self.assertEqual(self.calls('pg_ctl'), [])
        self.assertNotIn(password, self.db('init').stdout)

    def test_launcher_preserves_arguments_and_uses_project_config(self):
        self.assert_success(self.db('init'))
        (self.project / 'config.steamos.toml').touch()
        # The Python process itself is a boundary: record the real launch arguments.
        (self.bin / 'python').unlink()
        self.write_tool(self.bin / 'python')
        demo = str(self.root / 'demo with spaces.dem')
        self.assert_success(self.call('steamos.sh', 'process', demo))
        call = self.calls('python')[-1]
        self.assertEqual(call['args'], ['-m', 'cs_highlights', '--config',
                         str(self.project / 'config.steamos.toml'), 'process', demo])
        custom_config = self.root / 'other config.toml'
        custom_config.touch()
        self.assert_success(self.call('steamos.sh', 'smoke', demo, CSH_CONFIG=str(custom_config)))
        self.assertEqual(self.calls('python')[-1]['args'],
                         [str(self.project / 'scripts/smoke_linux.py'), '--config', str(custom_config), demo])

    def test_gui_receives_local_psql_on_path(self):
        self.assert_success(self.db('init'))
        csdm = self.install / 'csdm-3.20.1'
        csdm.mkdir()
        self.write_tool(csdm / 'AppRun')
        self.assert_success(self.call('steamos.sh', 'csdm', DISPLAY=':0'))
        self.assertTrue(self.calls('AppRun')[0]['path'].startswith(f'{self.bin}:'))
        self.assertTrue((self.state / 'running').exists())


if __name__ == '__main__':
    unittest.main()
